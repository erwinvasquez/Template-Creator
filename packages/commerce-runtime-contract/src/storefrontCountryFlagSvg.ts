const pending = new Map<string, Promise<string | null>>();

export function loadStorefrontCountryFlag(iso: string): Promise<string | null> {
  const key = iso.trim().toUpperCase();
  const cached = pending.get(key);
  if (cached) return cached;
  const load = FLAG_LOADERS[key];
  const promise = load ? load().catch(() => null) : Promise.resolve(null);
  pending.set(key, promise);
  return promise;
}
